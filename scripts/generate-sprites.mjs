function render(row) {
  const era = eras.get(row.id) ?? "early"
  const picture = scenes[row.id]?.() ?? r(40, 40, 160, 100, "#fff", 8)
  const lines = wrapName(row.name)
  const label =
    lines.length === 1
      ? tx(128, 234, lines[0], 15, "#f4efe4")
      : tx(128, 224, lines[0], 13, "#f4efe4") + tx(128, 242, lines[1], 13, "#f4efe4")
  return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" viewBox="0 0 256 256" role="img">
  <title>${esc(row.subject)}</title>
  <rect width="256" height="256" fill="${eraBg[era]}"/>
  <rect x="6" y="6" width="244" height="186" rx="22" fill="#07080c" stroke="${eraAccent[era]}" stroke-width="5"/>
  <clipPath id="frame"><rect x="12" y="12" width="232" height="174" rx="16"/></clipPath>
  <g clip-path="url(#frame)">${picture}</g>
  <rect x="6" y="198" width="244" height="52" rx="14" fill="#07080c"/>
  ${label}
</svg>
`
}

const outDir = path.join(root, "public/sprites")
fs.mkdirSync(outDir, { recursive: true })
if (subjects.length !== 48) {
  console.error(`expected 48 subjects, found ${subjects.length}`)
  process.exit(1)
}
for (const row of subjects) {
  if (!scenes[row.id]) {
    console.error(`missing scene ${row.id}`)
    process.exit(1)
  }
  fs.writeFileSync(path.join(outDir, `${row.id}.svg`), render(row))
}
console.log(`wrote ${subjects.length} sprites`)
