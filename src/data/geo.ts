/** One share of the audience: the people in a city, as a share of all requests. They sum to 1. */
export interface AudienceShare {
  readonly city: string
  readonly share: number
}

const EARTH_KM = 6371

export function distanceKm(a: City, b: City): number {
  const rad = Math.PI / 180
  const dLat = (b.lat - a.lat) * rad
  const dLon = (b.lon - a.lon) * rad
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(a.lat * rad) * Math.cos(b.lat * rad) * Math.sin(dLon / 2) ** 2
  return 2 * EARTH_KM * Math.asin(Math.min(1, Math.sqrt(h)))
}

/** A request's round trips to a region `km` away: a fixed cost plus the time light takes through fibre. */
